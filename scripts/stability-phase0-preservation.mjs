import fs from 'node:fs';
import {createHash} from 'node:crypto';
const d='docs/evidence/stability-phase0/';
const before=JSON.parse(fs.readFileSync(d+'production-before.json','utf8').replace(/^\uFEFF/,''));
const sha=s=>createHash('sha256').update(s).digest('hex');
const unchanged=before.every(x=>sha(fs.readFileSync(x.path))===x.sha256);
const originalPaths=new Set(before.map(x=>x.path));
const newProductionFiles=fs.readdirSync('dist',{recursive:true,withFileTypes:true}).filter(x=>x.isFile()).map(x=>(x.parentPath+'/'+x.name).replaceAll('\\','/').replace(/^.*?dist\//,'dist/')).filter(x=>!originalPaths.has(x));
const result={originalAppByteIdentical:sha(fs.readFileSync('dist/app.mjs'))===before.find(x=>x.path==='dist/app.mjs').sha256,allExistingDistributionFilesByteIdentical:unchanged,newProductionFiles};
fs.writeFileSync(d+'preserved-source-check.json',JSON.stringify(result,null,2));console.log(result);
if(!unchanged||newProductionFiles.length)process.exitCode=1;
