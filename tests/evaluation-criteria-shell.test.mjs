import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createWorkspace,finalizeSavedWeaveRecord,createWeaveStudy,addInfluence,saveCarrierStudy,serializeWorkspace,parseBackup,validateTrustedWorkspace} from '../dist/document.mjs';
import {createRectangularCarrier} from '../dist/carrier.mjs';
import {refreshWeave} from '../dist/weave.mjs';
import {createAnalysisRun,appendAnalysisRun,createEvaluationRun,appendEvaluationRun,listSavedGenerationSettings,readAnalysisStatus,readCriterionRecords,readGeometryReadiness,validateGeneratorState} from '../dist/weave-record.mjs';

test('the detail shell reserves five criteria and reads stored status',()=>{
 const html=readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
 const app=readFileSync(new URL('../dist/app.mjs',import.meta.url),'utf8');
 assert.match(html,/GEOMETRY READINESS/);
 assert.match(html,/ANALYSIS STATUS/);
 assert.match(html,/EVALUATION STATUS/);
 assert.match(html,/SHARED ANALYSIS/);
 assert.match(html,/VERSION \/ PROVENANCE/);
 for(const id of ['WV-01','WV-02','WV-03','WV-04','WV-05'])assert.match(html,new RegExp(`data-criterion-status="${id}"`));
 assert.match(app,/readCriterionRecords/);
 assert.match(app,/readAnalysisStatus/);
 assert.match(app,/readGeometryReadiness/);
 assert.doesNotMatch(app.slice(app.indexOf('function renderEvaluationSetting'),app.indexOf('function renderEvaluationEvidence')),/family-spacing|influence-radius/);
 const ws=createWorkspace();
 let project=ws.projects[0];
 project.working.carrier=createRectangularCarrier();
 project=finalizeSavedWeaveRecord(project,'WEAVE A',{generatorVersion:'TEST-BUILD'}).project;
 const entry=project.carrierStudies[0];
 assert.equal(readAnalysisStatus(entry).status,'not-analyzed');
 assert.equal(readGeometryReadiness(project,entry).readiness,'ready');
 const fresh=readCriterionRecords(entry);
 assert.deepEqual(fresh.map(item=>item.criterionId),['WV-01','WV-02','WV-03','WV-04','WV-05']);
 assert.equal(fresh.every(item=>item.status==='not-evaluated'&&item.score===null),true);
 const artifact={artifactId:'artifact-1',version:'analysis-artifact-v1',weaveId:entry.weaveId,geometryFingerprint:'geometry-1',analysisRunId:'analysis-1'};
 appendAnalysisRun(entry,createAnalysisRun({analysisRunId:'analysis-1',geometryFingerprint:'geometry-1',status:'analyzed',artifacts:[artifact]}));
 const criterion=(id,status)=>({criterionId:id,status,normalizedScore:null,rating:null,components:{},safeguards:{},evidenceRefs:[],criterionLogicVersion:'logic-1',calibrationVersion:'calibration-1',warnings:[]});
 appendEvaluationRun(entry,createEvaluationRun({evaluationId:'evaluation-1',analysisRunId:'analysis-1',createdAt:'2026-09-27T12:00:00.000Z',status:'partial',criterionResults:{'WV-01':criterion('WV-01','evaluated'),'WV-05':criterion('WV-05','not-applicable')}}));
 assert.equal(readAnalysisStatus(entry).status,'analyzed');
 const stored=readCriterionRecords(entry);
 assert.equal(stored.find(item=>item.criterionId==='WV-01').status,'evaluated');
 assert.equal(stored.find(item=>item.criterionId==='WV-01').score,null);
 assert.equal(stored.find(item=>item.criterionId==='WV-05').status,'not-applicable');
 assert.equal(stored.find(item=>item.criterionId==='WV-03').status,'not-evaluated');
 assert.equal(stored.find(item=>item.criterionId==='WV-01').showRating,false);
 assert.match(html,/id="evaluation-detail-evaluate"/);
 assert.match(app,/evaluateWeave/);
 delete entry.revisions[0].strandIdentity;
 assert.equal(readGeometryReadiness(project,entry).readiness,'needsMigration');
 ws.projects[0]=project;
 assert.doesNotThrow(()=>validateTrustedWorkspace(ws));
});

test('failure and inapplicable criteria stay distinct from a valid low rating',()=>{
 const entry={weaveId:'weave-status',revisions:[],derivedAnalysis:{},evaluations:[],designerData:{},lineage:{}};
 const base={components:{},safeguards:{},evidenceRefs:[],warnings:[]};
 const failed={...base,criterionId:'WV-04',status:'evaluation-failed',normalizedScore:null,rating:null,criterionLogicVersion:'wv-04-logic-v1',calibrationVersion:'wv-04-calibration-v1',warnings:['WV-04 analysis evidence is missing.']};
 const low={...base,criterionId:'WV-02',status:'evaluated',normalizedScore:0,rating:1,components:{effectiveModulation:0},safeguards:{fieldRetention:1},submetrics:{m75:0,coverage:0},criterionLogicVersion:'wv-02-logic-v1',calibrationVersion:'wv-02-calibration-v1',explanation:'WV-02 scored 1.0/5.'};
 const skipped={...base,criterionId:'WV-05',status:'not-applicable',normalizedScore:null,rating:null,criterionLogicVersion:'wv-05-logic-v1',calibrationVersion:'wv-05-calibration-v1',explanation:'WV-05 needs at least two active families.'};
 appendEvaluationRun(entry,createEvaluationRun({evaluationId:'evaluation-status',analysisRunId:'analysis-status',createdAt:'2026-09-27T12:00:00.000Z',status:'partial',criterionResults:{'WV-02':low,'WV-04':failed,'WV-05':skipped}}));
 const records=readCriterionRecords(entry);
 const wv02=records.find(item=>item.criterionId==='WV-02');
 const wv04=records.find(item=>item.criterionId==='WV-04');
 const wv05=records.find(item=>item.criterionId==='WV-05');
 assert.equal(wv02.showRating,true);
 assert.equal(wv02.ratingText,'1.0');
 assert.match(wv02.reason,/barely bend the weave/);
 assert.match(wv02.reason,/kept their original direction/);
 assert.equal(wv02.evidence.some(([label])=>label.toLowerCase()==='m75'),true);
 assert.equal(wv04.showRating,false);
 assert.equal(wv04.reason,'');
 assert.equal(wv04.ratingText,'');
 assert.match(wv04.notice,/not a low rating/);
 assert.equal(wv05.showRating,false);
 assert.match(wv05.notice,/does not apply/);
 const coherent={weaveId:'weave-coherent',revisions:[],derivedAnalysis:{},evaluations:[],designerData:{},lineage:{}};
 appendEvaluationRun(coherent,createEvaluationRun({evaluationId:'evaluation-coherent',analysisRunId:'analysis-coherent',createdAt:'2026-09-27T12:00:00.000Z',status:'partial',criterionResults:{'WV-01':{...base,criterionId:'WV-01',status:'evaluated',normalizedScore:0.85,rating:4.4,components:{familyDistinctness:0.8,relationalCoupling:0.91},safeguards:{effectiveFamilyPresence:1},criterionLogicVersion:'wv-01-logic-v1',calibrationVersion:'wv-01-calibration-v1',explanation:'WV-01 scored 4.4/5.'},'WV-03':{...base,criterionId:'WV-03',status:'evaluated',normalizedScore:0.2,rating:1.8,components:{eventSalienceDifferentiation:0.2,spatialScaleHierarchy:0,recurrenceDifferentiation:0.1},safeguards:{eventViability:0.45},criterionLogicVersion:'wv-03-logic-v1',calibrationVersion:'wv-03-calibration-v1',explanation:'WV-03 scored 1.8/5.'}}}));
 const plain=readCriterionRecords(coherent);
 assert.match(plain.find(item=>item.criterionId==='WV-01').reason,/easy to tell apart/);
 assert.match(plain.find(item=>item.criterionId==='WV-01').reason,/cross and work together/);
 assert.match(plain.find(item=>item.criterionId==='WV-01').reason,/did not hold the score down/);
 assert.match(plain.find(item=>item.criterionId==='WV-03').reason,/held down/);
});

test('saved influences stay in the generator snapshot and display as one group',()=>{
 const ws=createWorkspace();
 let project=ws.projects[0];
 project.working.carrier=createRectangularCarrier();
 project=saveCarrierStudy(project,'PLAIN',{generatorVersion:'TEST-BUILD'}).project;
 const plain=project.carrierStudies[0].revisions[0].generation;
 assert.equal(Object.hasOwn(plain,'influences'),false);
 assert.doesNotThrow(()=>validateGeneratorState(plain));
 assert.equal(listSavedGenerationSettings(project.carrierStudies[0].revisions[0]).groups.length,0);
 project=createWeaveStudy(project,project.carrierStudies[0].latestRevisionId);
 project=addInfluence(project);
 project.working=refreshWeave(project.working,project.id);
 project=saveCarrierStudy(project,'PLAIN',{generatorVersion:'TEST-BUILD'}).project;
 const generation=project.carrierStudies[0].revisions.at(-1).generation;
 assert.equal(generation.influences.length,1);
 assert.equal(generation.influences[0].kind,'attractor');
 assert.equal(generation.influences[0].enabled,true);
 assert.equal(generation.influences[0].falloff,3);
 assert.equal(generation.influences[0].direction,0);
 assert.equal(generation.influences[0].families.A.strength,50);
 assert.equal(generation.influences[0].families.A.tension,0);
 assert.equal(typeof generation.influences[0].id,'string');
 assert.equal(Number.isFinite(generation.influences[0].radius),true);
 validateGeneratorState(generation);
 const listed=listSavedGenerationSettings(project.carrierStudies[0].revisions.at(-1));
 assert.equal(listed.groups.length,1);
 assert.equal(listed.groups[0].title,'INFLUENCE 1');
 const ids=listed.groups[0].rows.map(row=>row.parameterId);
 assert.ok(ids.includes('influence-type'));
 assert.ok(ids.includes('attractor-enabled'));
 assert.ok(ids.includes('influence-radius'));
 assert.ok(ids.includes('influence-strength'));
 assert.ok(ids.includes('influence-tension'));
 assert.equal(listed.groups[0].rows.every(row=>row.readOnly),true);
 ws.projects[0]=project;
 validateTrustedWorkspace(ws);
 const reloaded=parseBackup(serializeWorkspace(ws));
 assert.deepEqual(reloaded.projects[0].carrierStudies[0].revisions.at(-1).generation.influences,generation.influences);
});
