import test from 'node:test';
import assert from 'node:assert/strict';
import {createWorkspace,finalizeSavedWeaveRecord,duplicateLibraryItem} from '../dist/document.mjs';
import {createRectangularCarrier} from '../dist/carrier.mjs';
import {canonical} from '../dist/weave.mjs';
import {clearAnalysisCache} from '../dist/analysis.mjs';
import {evaluateWeave,reevaluateWeave,evaluateSelectedWeaves} from '../dist/evaluation.mjs';
import {compareEvaluationRecords,curateDesignerData,readWeaveIdentity,readWeaveLineage,readWeaveParent} from '../dist/weave-record.mjs';
import {evaluationDataset,parameterPattern,ADVISORY_BOUNDARY} from '../dist/parameter-analysis.mjs';
import {buildWeaveHandoff,recordWeaveHandoff} from '../dist/weave-handoff.mjs';

const NOW='2026-09-28T00:00:00.000Z';

test('the saved weave can be scored, compared, noted, and handed off without changing its geometry',async()=>{
 clearAnalysisCache();
 const ws=createWorkspace();
 let project=ws.projects[0];
 const carrier=createRectangularCarrier();
 carrier.generatorVersion='rect-v2';
 delete carrier.angleDegrees;
 carrier.families={A:{angleDegrees:0,spacing:50,offset:0,density:100},B:{angleDegrees:90,spacing:50,offset:0,density:100}};
 project.working.carrier=carrier;
 project=finalizeSavedWeaveRecord(project,'WORKFLOW',{now:NOW,generatorVersion:'TEST-BUILD'}).project;
 const entry=project.carrierStudies[0];
 const fingerprint=entry.revisions[0].geometryRef.geometryFingerprint;
 const scored=evaluateWeave(project,entry,{evaluationId:'evaluation-workflow',createdAt:NOW});
 assert.equal(Object.hasOwn(scored.evaluation,'overallScore'),false);
 assert.equal(scored.evaluation.criterionResults['WV-01'].status,'evaluated');
 assert.equal(scored.evaluation.criterionResults['WV-05'].status,'evaluated');
 const rating=scored.evaluation.criterionResults['WV-01'].rating;
 const geometry=canonical(entry.revisions);
 const stale=reevaluateWeave(project,entry,{stale:true});
 assert.deepEqual(stale.updated,[]);
 assert.equal(entry.evaluations.at(-1).criterionResults['WV-01'].rating,rating);
 project=duplicateLibraryItem(project,'pattern',entry.id,{recordsOnly:true});
 const child=project.carrierStudies[1];
 assert.equal(readWeaveParent(child).weaveId,readWeaveIdentity(entry).weaveId);
 assert.equal(entry.revisions[0].geometryRef.geometryFingerprint,fingerprint);
 assert.equal(canonical(entry.revisions),geometry);
 const compared=compareEvaluationRecords([entry,child]);
 assert.equal(compared.columns.length,2);
 assert.equal(compared.criteria.find(row=>row.id==='WV-01').different,true);
 const dataset=evaluationDataset(project.carrierStudies);
 const pattern=parameterPattern(dataset,{criterionId:'WV-01',outcome:'rating',parameter:'A SPACING',parameterB:''});
 assert.equal(ADVISORY_BOUNDARY.includes('do not replace evaluation'),true);
 assert.equal(entry.evaluations.at(-1).criterionResults['WV-01'].rating,rating);
 assert.equal(pattern.sampleSize>=0,true);
 entry.designerData=curateDesignerData(entry.designerData,{note:'keep',favorite:true});
 assert.equal(entry.evaluations.at(-1).criterionResults['WV-01'].rating,rating);
 assert.equal(canonical(entry.revisions),geometry);
 const sent=buildWeaveHandoff(project,entry,{handoffId:'handoff-workflow',createdAt:NOW});
 recordWeaveHandoff(entry,sent);
 const chain=readWeaveLineage(entry);
 assert.equal(chain.handoffs[0].handoffId,'handoff-workflow');
 assert.equal(chain.downstream[0].kind,'interpreter');
 assert.equal(chain.evaluated,'EVALUATED');
 assert.equal(canonical(entry.revisions),geometry);
 const batch=evaluateSelectedWeaves(project,[entry,child],{outdated:true});
 assert.equal(batch.updated.length,0);
 assert.equal(entry.evaluations.at(-1).criterionResults['WV-01'].rating,rating);
});
