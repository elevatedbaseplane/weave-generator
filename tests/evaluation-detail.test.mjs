import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {listSavedGenerationSettings} from '../dist/weave-record.mjs';
import {PARAMETER_DEFINITIONS,parameterDefinition,validateParameterDefinition} from '../dist/parameter-definitions.mjs';

test('a weave detail lists the saved generation settings for that record',()=>{
 const html=readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
 const app=readFileSync(new URL('../dist/app.mjs',import.meta.url),'utf8');
 assert.match(html,/id="evaluation-detail"/);
 assert.match(html,/BACK TO LIBRARY/);
 assert.match(html,/OPEN IN GENERATOR/);
 assert.match(html,/DUPLICATE/);
 assert.match(html,/DELETE/);
 assert.match(html,/NOT ANALYZED/);
 assert.match(app,/showEvaluationDetail/);
 assert.match(app,/duplicateLibraryItem\(project\(\),'pattern',entry\.id,\{recordsOnly:true\}\)/);
 assert.match(app,/deleteLibraryItem/);
 const listed=listSavedGenerationSettings({generation:{parameters:{families:{A:{spacing:40,offset:0,density:100,angleDegrees:12},B:{spacing:55,offset:1,density:80,angleDegrees:90}}},settings:{origin:{x:0,y:0},generatorVersion:'rect-v2',clipVersion:1,selectionVersion:1},modes:{kind:'rectangular'},seed:null,domain:{closed:true,points:[{x:0,y:0},{x:1,y:0},{x:0,y:1}]}}});
 const spacing=listed.rows.find(row=>row.label==='A SPACING');
 assert.equal(spacing.value,'40');
 assert.equal(spacing.parameterId,'family-spacing');
 assert.equal(spacing.type,'number');
 assert.equal(spacing.control,'slider');
 assert.equal(spacing.readOnly,true);
 assert.equal(spacing.min,parameterDefinition('family-spacing').min);
 assert.equal(spacing.max,parameterDefinition('family-spacing').max);
 const rotation=listed.rows.find(row=>row.label==='B ROTATION');
 assert.equal(rotation.value,'90');
 assert.equal(rotation.parameterId,'family-angle');
 assert.equal(rotation.control,'slider');
 const density=listed.rows.find(row=>row.label==='A DENSITY');
 assert.equal(density.type,'integer');
 assert.equal(density.control,'number');
 assert.equal(density.value,'100');
 assert.equal(listed.rows.find(row=>row.parameterId==='variation-seed').value,'NONE');
 assert.equal(listed.note,'');
 assert.match(app,/renderEvaluationSetting/);
 assert.match(app,/row\.control==='slider'/);
 assert.match(app,/bar\.disabled=true/);
 const missing=listSavedGenerationSettings({});
 assert.equal(missing.rows.length,0);
 assert.match(missing.note,/UNAVAILABLE/);
 const setting=app.slice(app.indexOf('function renderEvaluationSetting'),app.indexOf('function renderEvaluationDetail'));
 assert.doesNotMatch(setting,/family-spacing|family-angle|edge-bias/);
});

test('evaluation display follows a changed or added parameter definition',()=>{
 const renamed={...parameterDefinition('family-spacing'),label:'PITCH'};
 const registry={...PARAMETER_DEFINITIONS,'family-spacing':renamed,'edge-bias':validateParameterDefinition({id:'edge-bias',label:'EDGE BIAS',type:'number',min:0,max:5,step:0.5,default:1}),'show-guides':validateParameterDefinition({id:'show-guides',label:'SHOW GUIDES',type:'boolean',default:false}),'edge-mode':validateParameterDefinition({id:'edge-mode',label:'EDGE MODE',type:'enum',options:['tight','loose'],default:'tight'})};
 const listed=listSavedGenerationSettings({generation:{parameters:{families:{A:{spacing:40,offset:0,density:100,angleDegrees:12}},'edge-bias':2.5,'show-guides':true,'edge-mode':'loose'},settings:{origin:{x:0,y:0},generatorVersion:'rect-v2',clipVersion:1,selectionVersion:1},modes:{kind:'rectangular'},seed:null,domain:{closed:true,points:[{x:0,y:0},{x:1,y:0},{x:0,y:1}]}}},registry);
 const pitch=listed.rows.find(row=>row.parameterId==='family-spacing');
 assert.equal(pitch.label,'A PITCH');
 assert.equal(pitch.value,'40');
 assert.equal(pitch.control,'slider');
 assert.equal(pitch.readOnly,true);
 const bias=listed.rows.find(row=>row.parameterId==='edge-bias');
 assert.equal(bias.label,'EDGE BIAS');
 assert.equal(bias.value,'2.5');
 assert.equal(bias.min,0);
 assert.equal(bias.max,5);
 assert.equal(bias.control,'slider');
 assert.equal(listed.rows.find(row=>row.parameterId==='show-guides').value,'ON');
 assert.equal(listed.rows.find(row=>row.parameterId==='show-guides').control,'boolean');
 assert.equal(listed.rows.find(row=>row.parameterId==='edge-mode').value,'loose');
 assert.equal(listed.rows.find(row=>row.parameterId==='edge-mode').control,'enum');
 assert.equal(parameterDefinition('family-spacing').label,'SPACING');
});
